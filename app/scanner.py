_PRESERVED = ("ra_game_id", "title_override", "meta", "meta_manual")


def load_library():
    try:
        data = json.loads(LIBRARY_FILE.read_text())
        return data.get("games", [])
    except Exception:  # noqa: BLE001
        return []


def save_library(games):
    LIBRARY_FILE.write_text(json.dumps({"games": games}, indent=2))


def rescan(roots):
    """Scan and merge with the stored library, preserving cached RA
    matches and manual overrides for games that are still there."""
    old = {g["folder"]: g for g in load_library()}
    games = scan_roots(roots)
    for g in games:
        prev = old.get(g["folder"])
        if prev:
            for key in _PRESERVED:
                if prev.get(key) is not None:
                    g[key] = prev[key]
        else:
            g.setdefault("title_override", None)
    save_library(games)
    return games


def display_title(game):
    return game.get("title_override") or game["title"]


# ------------------------------------------------------------------
# RetroAchievements token supply + launching
# ------------------------------------------------------------------
def ra_toml_text(username, token, hardcore):
    """The exact format the shipped games read (username/api_token in
    double quotes, hardcore unquoted)."""
    def q(s):
        return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'
    return ("# RetroAchievements login, written by Recomp Launcher from\n"
            "# the credentials saved in its Settings.\n"
            f"username = {q(username)}\n"
            f"api_token = {q(token)}\n"
            f"hardcore = {'true' if hardcore else 'false'}\n")


def supply_ra_toml(game, settings):
    """Write retroachievements.toml next to the game if it has none
    and token supply is configured. Never overwrites an existing
    file. Returns True when a file was written."""
    if not game.get("ra_supported", True):
        return False
    folder = Path(game["folder"])
    target = folder / "retroachievements.toml"
    if target.exists():
        return False
    username = (settings.get("ra_username") or "").strip()
    token = (settings.get("ra_connect_token") or "").strip()
    if not username or not token:
        return False
    target.write_text(ra_toml_text(username, token,
                                   settings.get("hardcore", True)))
    return True


def launch_game(game, settings, log_dir, extra_env=None):
    """Supply the RA toml if needed, then start the game detached
    with its own folder as cwd. Returns (Popen, supplied_toml).

    extra_env: environment additions for this launch only (the
    game-capture variables); merged over a copy of os.environ,
    never written into the launcher's own environment."""
    child_env = None
    if extra_env:
        child_env = dict(os.environ)
        child_env.update({str(k): str(v)
                          for k, v in extra_env.items()})
    supplied = supply_ra_toml(game, settings)
    if supplied:
        game["has_ra_toml"] = True
    folder = Path(game["folder"])
    target = Path(game["launch"])
    if sys.platform != "win32":
        # Packages copied off FAT drives or out of plain zipfile
        # extractions can lose their execute bits; the play scripts
        # also exec the binary by relative path, so heal every ELF
        # in the folder, not just the direct target.
        try:
            for f in folder.iterdir():
                if f.is_file() and f.suffix.lower() != ".exe" \
                        and _is_elf(f) and not os.access(f, os.X_OK):
                    f.chmod(0o755)
        except Exception:  # noqa: BLE001
            pass
    if game["launch_kind"] == "script":
        cmd = ["/bin/sh", str(target)]
    else:
        cmd = [str(target)]
    log_dir = Path(log_dir)
    log_dir.mkdir(parents=True, exist_ok=True)
    safe = re.sub(r"[^A-Za-z0-9]+", "-", display_title(game)).strip("-")
    logf = open(log_dir / f"{safe}.log", "ab")  # noqa: SIM115
    proc = subprocess.Popen(cmd, cwd=str(folder), start_new_session=True,
                            stdout=logf, stderr=subprocess.STDOUT,
                            env=child_env)
    return proc, supplied
