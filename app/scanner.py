"""Recomp Launcher — library scanner.

Detects recomp game packages in user-chosen root folders. Every
detector here is built from the on-disk layout of the real shipped
packages (inspected 2026-11-03):

  PSX      game.toml with [game] id = "SLUS-00005" serial and
           exe = "disc/..." (+ artwork/<serial>/front.png, bios/)
  GBA      game.toml generated by GBARecomp Tools ([program] section,
           [identity] sha1/md5), folder "<Title> (GBA)"
  NES      README first line "... (NESRecomp, cycle backend)",
           assets/img/boxart.tga, exe named after the game;
           game-cycle.toml when pointed at a project dir
  SNES     README first line "... (SNESRecomp)", assets/ + mods/
  GB       README first line "... (GBRecomp)"; older builds:
           assets/img/brand_gb.tga / brand_gbc.tga
  N64      Zelda64Recompiled binary / assets/launcher.rml,
           README "... (N64Recomp + N64ModernRuntime)"
  Genesis  README "... (GenesisRecomp Tools)", folder "(Genesis)"
  VB       README "... (VBRecomp Tools)", folder "(Virtual Boy)",
           *.vbmod module files
  SMS / GG README "... (SMSGGRecomp Tools)", folder "(Master System)"
           / "(Game Gear)", play.sh + <Game>Recomp binary

A directory only counts as a game when a family detector matches AND
a launchable binary (ELF or .exe) or play script is present — that
keeps converter *-src project folders (which carry a game.toml but
no built binary) out of the library.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
LIBRARY_FILE = APP_DIR / "library.json"

# system key -> (display name, RetroAchievements console ID).
# Console IDs verified against the RA Web API docs 2026-11-03
# (API_GetConsoleIDs; PlayStation = 12 per RA's own system table,
# Mega Drive = 1 matches the docs' worked examples).
SYSTEMS = {
    "psx": ("PlayStation", 12),
    "nes": ("NES", 7),
    "snes": ("SNES", 3),
    "gb": ("Game Boy", 4),
    "gbc": ("Game Boy Color", 6),
    "gba": ("Game Boy Advance", 5),
    "n64": ("Nintendo 64", 2),
    "genesis": ("Genesis / Mega Drive", 1),
    "sms": ("Master System", 11),
    "gg": ("Game Gear", 15),
    "vb": ("Virtual Boy", 28),
}
SYSTEM_ORDER = ["psx", "nes", "snes", "gb", "gbc", "gba", "n64",
                "genesis", "sms", "gg", "vb"]
# The N64 runtime (Zelda64Recomp) has no RetroAchievements hook
# surface, so its packages never carry a retroachievements.toml and
# the launcher must not write one or promise RA progress for them.
RA_UNSUPPORTED = {"n64"}

_FOLDER_SUFFIX_SYSTEMS = {
    "(Genesis)": "genesis",
    "(Virtual Boy)": "vb",
    "(Master System)": "sms",
    "(Game Gear)": "gg",
    "(GBA)": "gba",
}

_SERIAL_RE = re.compile(r"^[A-Z]{4}[-_][0-9]{3}(\.[0-9]{2})?$|^[A-Z]{4}-[0-9]{5}$")


# ------------------------------------------------------------------
# small file helpers
# ------------------------------------------------------------------
def _read_text(path, limit=20000):
    try:
        return Path(path).read_text(errors="replace")[:limit]
    except Exception:  # noqa: BLE001
        return ""


def _first_line(path):
    for line in _read_text(path, 2000).splitlines():
        if line.strip():
            return line.strip()
    return ""


def _toml_value(text, section, key):
    """Tiny TOML scalar reader (quoted string or bare value)."""
    in_section = section is None
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("[") and s.endswith("]"):
            in_section = (s.strip("[]").strip() == section)
            continue
        if in_section:
            m = re.match(re.escape(key) + r'\s*=\s*"([^"]*)"', s)
            if m:
                return m.group(1)
            m = re.match(re.escape(key) + r"\s*=\s*(\S+)", s)
            if m:
                return m.group(1)
    return None


def _is_elf(path):
    try:
        with open(path, "rb") as f:
            return f.read(4) == b"\x7fELF"
    except Exception:  # noqa: BLE001
        return False


def _find_binary(folder):
    """The launchable program in a package folder: an ELF executable
    or a Windows .exe at the top level. Prefers a name that matches
    the folder, then the largest candidate."""
    cands = []
    try:
        entries = sorted(Path(folder).iterdir())
    except Exception:  # noqa: BLE001
        return None
    for f in entries:
        if not f.is_file():
            continue
        if f.suffix.lower() == ".exe" or _is_elf(f):
            cands.append(f)
    if not cands:
        return None
    stem = re.sub(r"[^A-Za-z0-9]", "", Path(folder).name).lower()
    for f in cands:
        if re.sub(r"[^A-Za-z0-9]", "", f.stem).lower() == stem:
            return f
    cands.sort(key=lambda f: -f.stat().st_size)
    return cands[0]


def _artwork(folder):
    """artwork/<key>/front.png — the key is the display title for the
    cartridge families, the disc serial for PSX."""
    art_dir = Path(folder) / "artwork"
    if art_dir.is_dir():
        for sub in sorted(art_dir.iterdir()):
            front = sub / "front.png"
            if sub.is_dir() and front.is_file():
                return front, sub.name
    return None, None


def _strip_system_suffix(name):
    for suffix in _FOLDER_SUFFIX_SYSTEMS:
        if name.endswith(suffix):
            return name[: -len(suffix)].strip()
    return name


def _title_from_readme(line):
    """Parse the display title out of a converter README first line."""
    for pat in (r"^(.+?)\s+—\s+native PC recompilation",
                r"^(.+?)\s+-\s+native PC recompilation",
                r"^(.+?)\s+-\s+native PC recomp\b",
                r"^(.+?)\s+—\s+Recompiled for PC"):
        m = re.match(pat, line)
        if m:
            title = m.group(1).strip().lstrip("#").strip()
            # Drop a trailing "(Game Boy)"-style system tag.
            title = re.sub(r"\s+\((Game Boy|Game Boy Color|Master System|"
                           r"Game Gear|Genesis|Virtual Boy|GBA)\)\s*$",
                           "", title)
            if title.isupper():
                title = title.title()
            return title
    return None


# ------------------------------------------------------------------
# detection
# ------------------------------------------------------------------
def detect_game(folder):
    """Return a game record dict if `folder` is a recomp package,
    else None."""
    folder = Path(folder)
    if not folder.is_dir():
        return None
    try:
        names = {p.name for p in folder.iterdir()}
    except Exception:  # noqa: BLE001
        return None

    readme_line = ""
    for cand in ("README.txt", "README.md"):
        if cand in names:
            readme_line = _first_line(folder / cand)
            if readme_line:
                break

    front, art_key = _artwork(folder)
    system = None
    title = None
    title_from_readme = False
    serial = None

    toml_text = _read_text(folder / "game.toml") if "game.toml" in names else ""

    if "game-cycle.toml" in names:
        system = "nes"
        title = _toml_value(_read_text(folder / "game-cycle.toml"),
                            "game", "name")
    elif toml_text:
        game_id = _toml_value(toml_text, "game", "id")
        if ("GBARecomp" in toml_text or "[identity]" in toml_text
                or folder.name.endswith("(GBA)")):
            system = "gba"
            title = _toml_value(toml_text, "game", "name")
        elif game_id and _SERIAL_RE.match(game_id):
            system = "psx"
            serial = game_id
            title = _toml_value(toml_text, "game", "name")
        elif "disc/" in toml_text or "[game]" in toml_text:
            system = "psx"
            title = _toml_value(toml_text, "game", "name")
            serial = game_id

    if system is None and readme_line:
        if "(NESRecomp" in readme_line:
            system = "nes"
        elif "(SNESRecomp)" in readme_line:
            system = "snes"
        elif "(GBRecomp)" in readme_line:
            system = "gb"
        elif "(SMSGGRecomp Tools)" in readme_line:
            if "Game Gear" in readme_line or folder.name.endswith("(Game Gear)"):
                system = "gg"
            else:
                system = "sms"
        elif "(GenesisRecomp Tools)" in readme_line:
            system = "genesis"
        elif "(VBRecomp Tools)" in readme_line:
            system = "vb"
        elif "(N64Recomp" in readme_line:
            system = "n64"
        elif "(Game Boy Advance)" in readme_line:
            system = "gba"
        if system:
            parsed = _title_from_readme(readme_line)
            if parsed and not title:
                title = parsed
                title_from_readme = True

    if system is None:
        for suffix, syskey in _FOLDER_SUFFIX_SYSTEMS.items():
            if folder.name.endswith(suffix):
                system = syskey
                break
    if system is None and ("Zelda64Recompiled" in names
                           or (folder / "assets" / "launcher.rml").is_file()):
        system = "n64"
    if system is None and any(n.endswith(".vbmod") for n in names):
        system = "vb"
    if system is None and ((folder / "assets" / "img" / "brand_gb.tga").is_file()
                           or (folder / "assets" / "img" / "brand_gbc.tga").is_file()):
        # Legacy GB builds (e.g. the Tetris link-play test build)
        # predate the (GBRecomp) README marker.
        system = "gbc" if "Game Boy Color" in readme_line else "gb"
        parsed = _title_from_readme(readme_line)
        if parsed and not title:
            title = parsed
            title_from_readme = True

    if system is None:
        return None

    binary = _find_binary(folder)
    play_script = folder / "play.sh"
    if system in ("sms", "gg") and play_script.is_file():
        launch, launch_kind = play_script, "script"
    elif binary is not None:
        launch, launch_kind = binary, "binary"
    elif play_script.is_file():
        launch, launch_kind = play_script, "script"
    else:
        return None     # detector matched but nothing launchable

    # Artwork keys are the curated No-Intro display titles; they beat
    # a README parse (Genesis/VB READMEs embed ROM revision strings),
    # but never a name from the package's own game.toml.
    if art_key and not _SERIAL_RE.match(art_key) \
            and (not title or title_from_readme):
        title = art_key
    if not title:
        title = _strip_system_suffix(folder.name)

    return {
        "id": hashlib.sha1(str(folder).encode()).hexdigest()[:16],
        "title": title,
        "system": system,
        "folder": str(folder),
        "launch": str(launch),
        "launch_kind": launch_kind,
        "art": str(front) if front else None,
        "has_ra_toml": (folder / "retroachievements.toml").is_file(),
        "ra_supported": system not in RA_UNSUPPORTED,
        "serial": serial,
        "ra_game_id": None,
    }


def scan_roots(roots, max_depth=4):
    """Walk each root; a directory that detects as a game is a leaf."""
    games = []
    seen = set()
    for root in roots:
        if not str(root).strip():
            continue            # "" would walk the working directory
        root = Path(root).expanduser()
        if not root.is_dir():
            continue
        for dirpath, dirnames, _files in os.walk(root):
            depth = len(Path(dirpath).relative_to(root).parts) \
                if Path(dirpath) != root else 0
            game = detect_game(dirpath)
            if game:
                if game["folder"] not in seen:
                    seen.add(game["folder"])
                    games.append(game)
                dirnames[:] = []
            elif depth >= max_depth:
                dirnames[:] = []
            else:
                # Don't descend into converter project/build trees.
                dirnames[:] = [d for d in dirnames
                               if not d.endswith("-src")
                               and d not in ("build", "build-linux",
                                             "build-win", "_deps")]
    games.sort(key=lambda g: (SYSTEM_ORDER.index(g["system"])
                              if g["system"] in SYSTEM_ORDER else 99,
                              g["title"].lower()))
    return games


